#!/usr/bin/env node
// Generates src/constants/assets/registry.generated.ts from assets-manifest.json,
// so the app never scatters require() calls for assets.
//
//   npm run assets:registry        (also runs after npm run assets:optimize)
//
// Metro only bundles assets referenced by static require()/import strings, which is
// why this is code generation instead of reading the manifest at runtime.

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const MANIFEST = join(ROOT, 'assets-manifest.json');
const OUTPUT = join(ROOT, 'src/constants/assets/registry.generated.ts');

// Manifest category -> key prefix stripped from asset ids.
const CATEGORIES = {
  mascots: { prefix: 'milo-', kind: 'image' },
  journey: { prefix: 'journey-', kind: 'image' },
  chapters: { prefix: /^chapter-\d+-/, kind: 'image' },
  badges: { prefix: 'badge-', kind: 'image' },
  quests: { prefix: 'quest-', kind: 'vector' },
  emptyStates: { prefix: '', kind: 'image' },
  effects: { prefix: '', kind: 'image' },
  sounds: { prefix: '', kind: 'sound' },
};

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function toKey(category, id) {
  const { prefix } = CATEGORIES[category];
  let base =
    prefix instanceof RegExp
      ? id.replace(prefix, '')
      : id.startsWith(prefix)
        ? id.slice(prefix.length)
        : id;
  // "3-days" -> "days-3" so keys stay valid identifiers ("days3", "words100").
  base = base.replace(/^(\d+)-(.+)$/, '$2-$1');
  return base.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());
}

const pascal = (value) => value.charAt(0).toUpperCase() + value.slice(1);

function assertEntry(category, id, entry) {
  const where = `${category}.${id}`;
  if (typeof entry.file !== 'string' || !entry.file.startsWith('assets/'))
    throw new Error(`${where}: invalid "file"`);
  if (typeof entry.status !== 'string') throw new Error(`${where}: missing "status"`);
  if (CATEGORIES[category].kind !== 'sound' && !(entry.width > 0 && entry.height > 0)) {
    throw new Error(`${where}: width/height must be positive`);
  }
}

async function main() {
  const manifest = JSON.parse(await readFile(MANIFEST, 'utf8'));
  const importPath = (file) => relative(dirname(OUTPUT), join(ROOT, file)).split('\\').join('/');

  const imports = [];
  const sections = [];
  const keyTypes = [];

  for (const [category, { kind }] of Object.entries(CATEGORIES)) {
    const entries = Object.entries(manifest[category] ?? {}).sort(([a], [b]) => a.localeCompare(b));
    if (!entries.length) throw new Error(`assets-manifest.json has no "${category}" entries`);
    const seen = new Set();
    const lines = [];

    for (const [id, entry] of entries) {
      assertEntry(category, id, entry);
      const key = toKey(category, id);
      if (!IDENTIFIER.test(key))
        throw new Error(`${category}.${id}: derived key "${key}" is not a valid identifier`);
      if (seen.has(key)) throw new Error(`${category}: duplicate key "${key}"`);
      seen.add(key);

      const path = importPath(entry.file);
      const doc = `/** ${entry.file} · ${entry.width ? `${entry.width}×${entry.height} · ` : ''}${entry.status} */`;
      if (kind === 'vector') {
        const component = `Svg${pascal(category)}${pascal(key)}`;
        imports.push(`import ${component} from '${path}';`);
        lines.push(
          doc,
          `${key}: { kind: 'vector', Component: ${component}, width: ${entry.width}, height: ${entry.height}, status: '${entry.status}' },`,
        );
      } else if (kind === 'sound') {
        const durationMs = Math.round(entry.durationMs ?? entry.audio?.production?.durationMs ?? 0);
        lines.push(
          doc,
          `${key}: { kind: 'sound', source: require('${path}'), durationMs: ${durationMs}, status: '${entry.status}' },`,
        );
      } else {
        lines.push(
          doc,
          `${key}: { kind: 'image', source: require('${path}'), width: ${entry.width}, height: ${entry.height}, hasAlpha: ${Boolean(entry.hasAlpha)}, status: '${entry.status}' },`,
        );
      }
    }

    const type = { image: 'ImageAsset', vector: 'VectorAsset', sound: 'SoundAsset' }[kind];
    sections.push(
      `export const ${category} = {\n${lines.join('\n')}\n} as const satisfies Record<string, ${type}>;`,
    );
    keyTypes.push(
      `export type ${pascal(category).replace(/s$/, '')}Key = keyof typeof ${category};`,
    );
  }

  const missing = (manifest.missing ?? []).map(
    (m) => `{ category: '${m.category}', expected: '${m.expected}' },`,
  );

  const source = `// AUTO-GENERATED by scripts/generate-asset-registry.mjs from assets-manifest.json.
// Do not edit by hand. Regenerate with: npm run assets:registry

import type { ImageAsset, MissingAsset, SoundAsset, VectorAsset } from './types';
${imports.join('\n')}

${sections.join('\n\n')}

/** Assets the app expects but that do not exist yet (see ASSET_MANIFEST.md). */
export const missingAssets = [
${missing.join('\n')}
] as const satisfies readonly MissingAsset[];

${keyTypes.join('\n')}
`;

  const options = (await prettier.resolveConfig(OUTPUT)) ?? {};
  const formatted = await prettier.format(source, { ...options, parser: 'typescript' });
  await writeFile(OUTPUT, formatted);
  const counts = Object.keys(CATEGORIES)
    .map((c) => `${c} ${Object.keys(manifest[c] ?? {}).length}`)
    .join(', ');
  console.log(`✓ ${relative(ROOT, OUTPUT)} (${counts}; missing ${missing.length})`);
}

main().catch((error) => {
  console.error(`✗ ${error.message}`);
  process.exitCode = 1;
});
